package main

import (
	"context"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"log"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"

	"github.com/nod/ntx/internal/auth"
	"github.com/nod/ntx/internal/config"
	"github.com/nod/ntx/internal/db"
	"github.com/nod/ntx/internal/handlers"
	"github.com/nod/ntx/internal/models"
	"github.com/nod/ntx/internal/server"
	"github.com/spf13/cobra"
	"golang.org/x/term"
)

var version = "dev"

func main() {
	if err := rootCmd().Execute(); err != nil {
		os.Exit(1)
	}
}

func rootCmd() *cobra.Command {
	root := &cobra.Command{
		Use:   "ntx",
		Short: "personal site server",
	}

	serve := &cobra.Command{
		Use:   "serve",
		Short: "Start the HTTP server",
		RunE: func(cmd *cobra.Command, args []string) error {
			cfgFile, _ := cmd.Flags().GetString("config")
			cfg, err := config.Load(cfgFile)
			if err != nil {
				return err
			}

			database, err := db.Open(cfg.DBDSN)
			if err != nil {
				return err
			}
			sqlDB, err := database.DB()
			if err != nil {
				return err
			}
			defer sqlDB.Close()

			posts := models.NewPostStore(database)
			session := auth.NewSessionManager(cfg.SessionSecret, !cfg.Dev)

			srv, err := server.New(cfg, posts, session)
			if err != nil {
				return err
			}

			ctx, stop := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
			defer stop()

			go func() {
				log.Printf("listening on %s", srv.Addr)
				if err := srv.ListenAndServe(); err != nil {
					log.Printf("server stopped: %v", err)
				}
			}()

			<-ctx.Done()
			log.Printf("shutting down...")
			shutCtx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			defer cancel()
			return srv.Shutdown(shutCtx)
		},
	}
	serve.Flags().String("config", "", "config file (default: ntx.toml)")

	generate := &cobra.Command{
		Use:   "generate",
		Short: "Generate a static site from all content",
		RunE: func(cmd *cobra.Command, args []string) error {
			cfgFile, _ := cmd.Flags().GetString("config")
			outDir, _ := cmd.Flags().GetString("out")

			cfg, err := config.Load(cfgFile)
			if err != nil {
				return err
			}
			database, err := db.Open(cfg.DBDSN)
			if err != nil {
				return err
			}
			sqlDB, err := database.DB()
			if err != nil {
				return err
			}
			defer sqlDB.Close()

			posts := models.NewPostStore(database)
			session := auth.NewSessionManager(cfg.SessionSecret, !cfg.Dev)
			h, err := handlers.New(cfg, posts, session)
			if err != nil {
				return err
			}
			return h.Generate(outDir)
		},
	}
	generate.Flags().String("config", "", "config file (default: ntx.toml)")
	generate.Flags().String("out", "./out", "output directory")

	hashPw := &cobra.Command{
		Use:   "hash-password",
		Short: "Bcrypt a password for ntx.toml",
		RunE: func(cmd *cobra.Command, args []string) error {
			fmt.Fprint(os.Stderr, "Password: ")
			pw, err := term.ReadPassword(int(os.Stdin.Fd()))
			fmt.Fprintln(os.Stderr)
			if err != nil {
				return err
			}
			hash, err := auth.HashPassword(string(pw))
			if err != nil {
				return err
			}
			fmt.Println(hash)
			return nil
		},
	}

	genConfig := &cobra.Command{
		Use:   "gen-config",
		Short: "Print a sample ntx.toml to stdout",
		RunE: func(cmd *cobra.Command, args []string) error {
			promptPw, _ := cmd.Flags().GetBool("password")

			secret, err := randomSecret()
			if err != nil {
				return err
			}

			hash := ""
			if promptPw {
				fmt.Fprint(os.Stderr, "Password: ")
				pw, err := term.ReadPassword(int(os.Stdin.Fd()))
				fmt.Fprintln(os.Stderr)
				if err != nil {
					return err
				}
				hash, err = auth.HashPassword(string(pw))
				if err != nil {
					return err
				}
			}

			out := strings.ReplaceAll(sampleConfig, `session_secret      = ""`, fmt.Sprintf(`session_secret      = "%s"`, secret))
			if hash != "" {
				out = strings.ReplaceAll(out, `admin_password_hash = ""`, fmt.Sprintf(`admin_password_hash = "%s"`, hash))
			}
			fmt.Print(out)
			return nil
		},
	}
	genConfig.Flags().BoolP("password", "p", false, "prompt for admin password and embed bcrypt hash")

	versionCmd := &cobra.Command{
		Use:   "version",
		Short: "Print the version and exit",
		Run: func(cmd *cobra.Command, args []string) {
			fmt.Println(version)
		},
	}

	root.AddCommand(serve, generate, hashPw, genConfig, versionCmd)
	return root
}

const sampleConfig = `# ntx.toml — ntx server configuration
# Run 'ntx gen-config -p' to set admin_password_hash interactively.
# session_secret is auto-generated by gen-config.

site_name           = "mysite"
site_url            = "mysite.example.com"
site_description    = ""

static_path         = "./static"
db_dsn              = "sqlite://./ntx.db"
port                = 8080
bind_addr           = ""   # empty = localhost only; use "0.0.0.0" to listen on all interfaces
template_path       = "./templates"
about_slug          = "about"
admin_password_hash = ""   # required: bcrypt hash
session_secret      = ""   # required: random string, min 32 chars
dev                 = false
`

func randomSecret() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString(b), nil
}
