// readPasswordLine reads one newline-terminated password from r for
// the non-terminal branch of hash-password (scripted/CI use, e.g.
// `echo "$PW" | ntx hash-password`). It rejects an empty result: a
// closed or empty stdin yields io.EOF with no bytes read, which would
// otherwise silently hash the empty string and print a well-formed
// bcrypt hash that authenticates an empty password -- with no warning
// that nothing was actually read. See task-10 addendum, fix round 1.
func readPasswordLine(r io.Reader) (string, error) {
	line, err := bufio.NewReader(r).ReadString('\n')
	if err != nil && err != io.EOF {
		return "", err
	}
	pw := strings.TrimRight(line, "\r\n")
	if pw == "" {
		return "", fmt.Errorf("no password read from stdin")
	}
	return pw, nil
}

// applyGenConfigSubstitutions fills in the generated secret and, if a
// hash was computed, the first site's admin_password_hash. The hash
// substitution is anchored on the full site line including its
// trailing comment ("admin_password_hash = \"\"   # required: bcrypt
// hash") rather than the bare key-value pair: "admin_password_hash =
// \"\"" is a substring of the sample's commented
// "# global_admin_password_hash = \"\"" line, so a looser match would
// also rewrite that commented global line, silently granting
// all-sites admin access to whoever uncomments it. See task-10
// addendum, Ruling 7.
func applyGenConfigSubstitutions(sample, secret, hash string) string {
	out := strings.Replace(sample, `session_secret = ""`, fmt.Sprintf(`session_secret = "%s"`, secret), 1)
	if hash != "" {
		out = strings.Replace(out,
			`admin_password_hash = ""   # required: bcrypt hash`,
			fmt.Sprintf(`admin_password_hash = "%s"`, hash),
			1)
	}
	return out
}

func randomSecret() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.StdEncoding.EncodeToString(b), nil
}
