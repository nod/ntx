#!/bin/sh
# Print the Homebrew formula for an ntx release.
#
# Usage: scripts/gen-formula.sh <version> <checksums.txt> > Formula/ntx.rb
#
#   version        release version without the "v" (e.g. 0.7.2)
#   checksums.txt  `sha256sum ntx-*` output for the four release binaries
#
# NTX_RELEASE_BASE overrides where binaries are downloaded from (default: the
# GitHub release for <version>); set it to a file:// URL to test locally.

set -eu

[ $# -eq 2 ] || { echo "usage: $0 <version> <checksums.txt>" >&2; exit 2; }
version="$1"
sums="$2"
base="${NTX_RELEASE_BASE:-https://github.com/nod/ntx/releases/download/v${version}}"

sha() {
    s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
    [ -n "$s" ] || { echo "$0: no checksum for $1 in $sums" >&2; exit 1; }
    echo "$s"
}

darwin_arm64=$(sha ntx-darwin-arm64)
darwin_amd64=$(sha ntx-darwin-amd64)
linux_arm64=$(sha ntx-linux-arm64)
linux_amd64=$(sha ntx-linux-amd64)

cat <<FORMULA
# Generated by scripts/gen-formula.sh on release -- do not edit by hand.
class Ntx < Formula
  desc "Self-hosted personal site server: blog, content sections, admin UI"
  homepage "https://github.com/nod/ntx"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/ntx-darwin-arm64"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/ntx-darwin-amd64"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/ntx-linux-arm64"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/ntx-linux-amd64"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install Dir["ntx-*"].first => "ntx"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ntx version")
  end
end
FORMULA
